"""
BoreWise shared telemetry schema (v2) and validation.

Every producer (ESP32 firmware, Python simulator fleet, Streamlit dispatcher) and every
consumer (Lambda API, DynamoDB, analysis, web app) uses this one record format.

Depth is metres from the wellhead (0 m) down to the water surface; larger means deeper water.
While the pump runs the acoustic sounding is gated, so a record may carry
depth_to_water_m = null with measurement_valid = false.

data_source tags provenance so simulated numbers are never shown as field data:
- 'simulated': generated by simulator/physics.py
- 'bench-tested': ESP32 prototype on a bench or test-pipe rig
- 'field-measured': a real operational borewell
"""

from __future__ import annotations

import datetime
from typing import Any, Dict, Tuple

SCHEMA_VERSION = 2
VALID_DATA_SOURCES = {"simulated", "bench-tested", "field-measured"}
VALID_PUMP_STATES = {"ON", "OFF"}
VALID_EVENTS = {"pump_on", "pump_off", "dry_cutoff"}

DEPTH_MIN_M = 0.0
DEPTH_MAX_M = 300.0
TEMP_MIN_C = -10.0
TEMP_MAX_C = 80.0
CURRENT_MAX_A = 100.0
TAU_MAX_MS = 2000.0

REQUIRED_FIELDS = [
    "well_id", "timestamp", "data_source", "depth_to_water_m", "temperature_c",
    "pump_state", "pump_run_minutes", "measurement_valid",
]


def _is_number(v: Any) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def validate_telemetry_payload(payload: Dict[str, Any]) -> Tuple[bool, str]:
    """Returns (is_valid, error_message)."""
    if not isinstance(payload, dict):
        return False, "Payload must be a JSON object"

    for field in REQUIRED_FIELDS:
        if field not in payload:
            return False, f"Missing required field: '{field}'"

    if not isinstance(payload["well_id"], str) or not payload["well_id"].strip():
        return False, "Field 'well_id' must be a non-empty string"
    if len(payload["well_id"]) > 64 or "#" in payload["well_id"]:
        return False, "Field 'well_id' must be at most 64 characters and must not contain '#'"

    ts = payload["timestamp"]
    if not isinstance(ts, str):
        return False, "Field 'timestamp' must be an ISO 8601 string"
    try:
        parsed = datetime.datetime.fromisoformat(ts.replace("Z", "+00:00"))
    except ValueError:
        return False, f"Invalid ISO 8601 timestamp format: '{ts}'"
    if parsed.tzinfo is None:
        return False, "Field 'timestamp' must include a timezone (e.g. 'Z' or '+05:30')"

    if payload["data_source"] not in VALID_DATA_SOURCES:
        return False, f"Invalid 'data_source': '{payload['data_source']}'. Must be one of {sorted(VALID_DATA_SOURCES)}"

    if not isinstance(payload["measurement_valid"], bool):
        return False, "Field 'measurement_valid' must be a boolean"

    depth = payload["depth_to_water_m"]
    if depth is None:
        if payload["measurement_valid"]:
            return False, "Field 'depth_to_water_m' may only be null when 'measurement_valid' is false"
    else:
        if not _is_number(depth):
            return False, "Field 'depth_to_water_m' must be a numeric value or null"
        if depth < DEPTH_MIN_M or depth > DEPTH_MAX_M:
            return False, f"Field 'depth_to_water_m' ({depth}m) out of physical bounds [{DEPTH_MIN_M}m, {DEPTH_MAX_M}m]"

    temp = payload["temperature_c"]
    if not _is_number(temp):
        return False, "Field 'temperature_c' must be a numeric value"
    if temp < TEMP_MIN_C or temp > TEMP_MAX_C:
        return False, f"Field 'temperature_c' ({temp}°C) out of physical bounds [{TEMP_MIN_C}°C, {TEMP_MAX_C}°C]"

    if payload["pump_state"] not in VALID_PUMP_STATES:
        return False, f"Invalid 'pump_state': '{payload['pump_state']}'. Must be 'ON' or 'OFF'"

    run = payload["pump_run_minutes"]
    if not _is_number(run) or run < 0:
        return False, "Field 'pump_run_minutes' must be a non-negative number"

    # ---- optional v2 fields
    if payload.get("pump_current_a") is not None:
        cur = payload["pump_current_a"]
        if not _is_number(cur) or cur < 0 or cur > CURRENT_MAX_A:
            return False, f"Field 'pump_current_a' must be a number between 0 and {CURRENT_MAX_A:g} A"
    if payload.get("echo_tau_ms") is not None:
        tau = payload["echo_tau_ms"]
        if not _is_number(tau) or tau < 0 or tau > TAU_MAX_MS:
            return False, f"Field 'echo_tau_ms' must be a number between 0 and {TAU_MAX_MS:g} ms"
    if payload.get("event") is not None and payload["event"] not in VALID_EVENTS:
        return False, f"Invalid 'event': '{payload['event']}'. Must be one of {sorted(VALID_EVENTS)}"
    for text_field in ("fw", "scenario"):
        if payload.get(text_field) is not None and (not isinstance(payload[text_field], str) or len(payload[text_field]) > 64):
            return False, f"Field '{text_field}' must be a string of at most 64 characters"

    return True, ""


VALID_BORE_TYPES = {"open", "screen", "dug", "hand"}


def validate_well_config(cfg: Dict[str, Any]) -> Tuple[bool, str]:
    """Validates a well registration (POST /wells)."""
    if not isinstance(cfg, dict):
        return False, "Well config must be a JSON object"
    wid = cfg.get("well_id")
    if not isinstance(wid, str) or not wid.strip() or len(wid) > 64 or "#" in wid:
        return False, "Field 'well_id' must be a non-empty string of at most 64 characters without '#'"
    if cfg.get("bore_type", "open") not in VALID_BORE_TYPES:
        return False, f"Field 'bore_type' must be one of {sorted(VALID_BORE_TYPES)}"
    for key, lo, hi in (("depth_m", 5, 600), ("intake_m", 1, 600), ("pump_flow_m3_day", 0.1, 5000)):
        if key in cfg and (not _is_number(cfg[key]) or not lo <= cfg[key] <= hi):
            return False, f"Field '{key}' must be a number between {lo} and {hi}"
    if _is_number(cfg.get("intake_m")) and _is_number(cfg.get("depth_m")) and cfg["intake_m"] >= cfg["depth_m"]:
        return False, "Field 'intake_m' must be shallower than 'depth_m'"
    fr = cfg.get("fractures", [])
    if not isinstance(fr, list) or not all(isinstance(f, dict) and _is_number(f.get("d")) for f in fr):
        return False, "Field 'fractures' must be a list of objects with a numeric depth 'd'"
    rain = cfg.get("rain_mm", {})
    if not isinstance(rain, dict) or not all(isinstance(k, str) and _is_number(v) and v >= 0 for k, v in rain.items()):
        return False, "Field 'rain_mm' must map ISO dates to non-negative millimetres"
    return True, ""


def normalize_record(payload: Dict[str, Any]) -> Dict[str, Any]:
    """Store every timestamp in UTC ('...Z') so the DynamoDB sort key orders correctly."""
    out = dict(payload)
    ts = datetime.datetime.fromisoformat(payload["timestamp"].replace("Z", "+00:00"))
    out["timestamp"] = ts.astimezone(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    out["schema_version"] = SCHEMA_VERSION
    return out

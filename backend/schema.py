"""
BoreWise Shared Telemetry Schema & Data Validation Module

This module defines the validation rules and schema for telemetry payloads.
Supported data sources:
- 'simulated': Generated by Python physics simulator
- 'bench-tested': Physical prototype tested in small lab/bench rig
- 'field-measured': Actual readings from an operational borewell
"""

import datetime
from typing import Tuple, Dict, Any

VALID_DATA_SOURCES = {"simulated", "bench-tested", "field-measured"}
VALID_PUMP_STATES = {"ON", "OFF"}

# Depth reference point documentation:
# Depth is measured in metres from the wellhead top (0.0m) down to the water surface.
# Higher depth values represent deeper/lower water levels (drawdown).
DEPTH_MIN_M = 0.0
DEPTH_MAX_M = 300.0
TEMP_MIN_C = -10.0
TEMP_MAX_C = 80.0


def validate_telemetry_payload(payload: Dict[str, Any]) -> Tuple[bool, str]:
    """
    Validates a telemetry JSON payload.
    
    Returns:
        (is_valid: bool, error_message: str)
    """
    if not isinstance(payload, dict):
        return False, "Payload must be a JSON object"
        
    required_fields = [
        "well_id",
        "timestamp",
        "data_source",
        "depth_to_water_m",
        "temperature_c",
        "pump_state",
        "pump_run_minutes",
        "measurement_valid"
    ]
    
    for field in required_fields:
        if field not in payload:
            return False, f"Missing required field: '{field}'"
            
    # well_id
    if not isinstance(payload["well_id"], str) or not payload["well_id"].strip():
        return False, "Field 'well_id' must be a non-empty string"
        
    # timestamp
    timestamp_str = payload["timestamp"]
    if not isinstance(timestamp_str, str):
        return False, "Field 'timestamp' must be an ISO 8601 string"
    try:
        # Handle ISO timestamp strings ending in Z or offset
        ts = timestamp_str.replace("Z", "+00:00")
        datetime.datetime.fromisoformat(ts)
    except Exception:
        return False, f"Invalid ISO 8601 timestamp format: '{timestamp_str}'"
        
    # data_source
    data_source = payload["data_source"]
    if data_source not in VALID_DATA_SOURCES:
        return False, f"Invalid 'data_source': '{data_source}'. Must be one of {sorted(list(VALID_DATA_SOURCES))}"
        
    # depth_to_water_m
    depth = payload["depth_to_water_m"]
    if not isinstance(depth, (int, float)) or isinstance(depth, bool):
        return False, "Field 'depth_to_water_m' must be a numeric value"
    if depth < DEPTH_MIN_M or depth > DEPTH_MAX_M:
        return False, f"Field 'depth_to_water_m' ({depth}m) out of physical bounds [{DEPTH_MIN_M}m, {DEPTH_MAX_M}m]"
        
    # temperature_c
    temp = payload["temperature_c"]
    if not isinstance(temp, (int, float)) or isinstance(temp, bool):
        return False, "Field 'temperature_c' must be a numeric value"
    if temp < TEMP_MIN_C or temp > TEMP_MAX_C:
        return False, f"Field 'temperature_c' ({temp}°C) out of physical bounds [{TEMP_MIN_C}°C, {TEMP_MAX_C}°C]"
        
    # pump_state
    pump_state = payload["pump_state"]
    if pump_state not in VALID_PUMP_STATES:
        return False, f"Invalid 'pump_state': '{pump_state}'. Must be 'ON' or 'OFF'"
        
    # pump_run_minutes
    run_mins = payload["pump_run_minutes"]
    if not isinstance(run_mins, (int, float)) or isinstance(run_mins, bool) or run_mins < 0:
        return False, "Field 'pump_run_minutes' must be a non-negative number"
        
    # measurement_valid
    if not isinstance(payload["measurement_valid"], bool):
        return False, "Field 'measurement_valid' must be a boolean"
        
    return True, ""
